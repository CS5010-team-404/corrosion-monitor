package edu.neu.ecp.health.realdata;

import edu.neu.ecp.health.domain.HealthIssue;
import edu.neu.ecp.health.domain.HealthPolicy;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Replays the Intel Berkeley Lab readings through the seven sensor-health rules and scores them against the heuristic
 * reference of {@link ReferenceLabels}. Writes small result tables (Markdown + CSV) to the output directory.
 *
 * <pre>
 *   scripts/evaluate-health-intel-lab.sh      (wraps: --data data/intel/data.txt.gz --locs data/intel/mote_locs.txt)
 * </pre>
 * Deterministic: no randomness; motes are replayed in parallel but independently.
 */
public final class IntelLabEvaluation {

    static final Duration EXPECTED = Duration.ofSeconds(31);
    static final Duration EVERY = Duration.ofSeconds(5);

    /** A named rule configuration to replay. */
    record Variant(String name, String description, HealthPolicy policy) {
    }

    private IntelLabEvaluation() {
    }

    public static void main(String[] args) throws IOException {
        Path data = Path.of("data/intel/data.txt.gz");
        Path locs = Path.of("data/intel/mote_locs.txt");
        Path out = Path.of("docs/results");
        for (int i = 0; i < args.length; i++) {
            switch (args[i]) {
                case "--data" -> data = Path.of(args[++i]);
                case "--locs" -> locs = Path.of(args[++i]);
                case "--out" -> out = Path.of(args[++i]);
                default -> throw new IllegalArgumentException("unknown option " + args[i]);
            }
        }
        Files.createDirectories(out);
        IntelLabLoader.Data d = IntelLabLoader.load(data, locs);
        HealthPolicy def = HealthPolicy.defaults();
        List<Variant> variants = List.of(
                new Variant("defaults", "production defaults (HealthPolicy.defaults())", def),
                new Variant("indoor-range", "defaults, but plausible range 0..60 °C instead of the SHT31 limits -40..125 °C",
                        withTempRange(def, 0, 60)),
                new Variant("indoor-range+lossy-radio", "exploratory, chosen after seeing the defaults: indoor range, plus "
                        + "stuck-min-readings 10 (a 15-minute window holds about 29 readings at 31 s, far fewer with this "
                        + "radio's loss) and offline-factor 20 (about 10 minutes) so short radio drop-outs do not count as offline",
                        lossyRadio(withTempRange(def, 0, 60), 10, 20.0)));
        StringBuilder md = new StringBuilder("# Sensor health on real faults: Intel Berkeley Lab (generated)\n\n")
                .append("Generated by `scripts/evaluate-health-intel-lab.sh` (`edu.neu.ecp.health.realdata.IntelLabEvaluation`). ")
                .append("Do not edit by hand. Method and caveats: docs/SENSOR_HEALTH.md \"Real-data check\".\n\n")
                .append("Data: `").append(data.getFileName()).append("` SHA-256 `").append(sha256(data)).append("`, `")
                .append(locs.getFileName()).append("` SHA-256 `").append(sha256(locs)).append("`.\n\n");
        IntelLabLoader.Counts c = d.counts();
        md.append("| Lines | Malformed (not 8 fields / unparsable) | Mote id not in mote_locs | Repeated (mote, epoch) | Readings kept | Motes |\n")
          .append("|---|---|---|---|---|---|\n")
          .append(String.format(Locale.ROOT, "| %d | %d | %d | %d | %d | %d |%n%n", c.lines(), c.malformed(), c.unknownMote(),
                  c.duplicateEpoch(), c.kept(), d.motes().size()));
        Instant end = d.motes().values().stream().map(l -> l.get(l.size() - 1).at()).max(Comparator.naturalOrder()).orElseThrow();
        Instant start = d.motes().values().stream().map(l -> l.get(0).at()).min(Comparator.naturalOrder()).orElseThrow();
        md.append("Replay: ").append(start).append(" to ").append(end).append(", an evaluation every ").append(EVERY.toSeconds())
          .append(" s per mote from its first reading to the end of the data, expected interval ").append(EXPECTED.toSeconds())
          .append(" s, 15-minute window, 3 clean evaluations to close an issue (the production settings). ")
          .append(String.format(Locale.ROOT, "Epochs missing between each mote's first and last epoch: %.1f%% (radio loss).%n%n",
                  100 * lossShare(d)));
        StringBuilder csv = new StringBuilder("variant,detector,reference,tp,fp,fn,tn,precision,recall\n");
        StringBuilder epCsv = new StringBuilder("variant,mote,issue,start,end,minutes,evidence\n");
        for (Variant v : variants) {
            List<HealthReplay.Result> results = d.motes().entrySet().parallelStream()
                    .map(e -> HealthReplay.run(e.getKey(), e.getValue(), v.policy(), EXPECTED, EVERY, end))
                    .sorted(Comparator.comparingInt(HealthReplay.Result::mote)).toList();
            report(md, csv, epCsv, v, results);
        }
        md.append("CLOCK_SKEW and SIGNATURE_FAILURES cannot fire on this dataset (no receive times, no signatures).\n");
        Files.writeString(out.resolve("intel-lab-results.md"), md);
        Files.writeString(out.resolve("intel-lab-confusion.csv"), csv);
        Files.writeString(out.resolve("intel-lab-episode-examples.csv"), epCsv);
        System.out.println(md);
    }

    static HealthPolicy withTempRange(HealthPolicy p, double min, double max) {
        return new HealthPolicy(p.lateFactor(), p.offlineFactor(), p.window(), p.stuckMinReadings(), p.stuckEpsilon(),
                min, max, p.humidityMinPct(), p.humidityMaxPct(), p.outOfRangeMinCount(), p.spikeTempC(),
                p.spikeHumidityPct(), p.erraticMinSpikes(), p.lossyMissingPct(), p.lossyMinExpected(),
                p.signatureFailureMin(), p.clockSkewThreshold(), p.recoveryEvaluations(), p.startupGrace());
    }

    static HealthPolicy lossyRadio(HealthPolicy p, int stuckMin, double offlineFactor) {
        return new HealthPolicy(p.lateFactor(), offlineFactor, p.window(), stuckMin, p.stuckEpsilon(),
                p.tempMinC(), p.tempMaxC(), p.humidityMinPct(), p.humidityMaxPct(), p.outOfRangeMinCount(), p.spikeTempC(),
                p.spikeHumidityPct(), p.erraticMinSpikes(), p.lossyMissingPct(), p.lossyMinExpected(),
                p.signatureFailureMin(), p.clockSkewThreshold(), p.recoveryEvaluations(), p.startupGrace());
    }

    /** Share of epochs missing between each mote's first and last epoch (restarts ignored), pooled. */
    static double lossShare(IntelLabLoader.Data d) {
        long span = 0;
        long got = 0;
        for (List<IntelLabLoader.Reading> l : d.motes().values()) {
            long min = l.stream().mapToLong(IntelLabLoader.Reading::epoch).min().orElse(0);
            long max = l.stream().mapToLong(IntelLabLoader.Reading::epoch).max().orElse(0);
            span += max - min + 1;
            got += l.size();
        }
        return span == 0 ? 0 : 1 - (double) got / span;
    }

    static void report(StringBuilder md, StringBuilder csv, StringBuilder epCsv, Variant v, List<HealthReplay.Result> rs) {
        long ticks = rs.stream().mapToLong(HealthReplay.Result::ticks).sum();
        double moteHours = ticks * EVERY.toSeconds() / 3600.0;
        md.append("## Variant: ").append(v.name()).append("\n\n").append(v.description()).append(". ")
          .append(String.format(Locale.ROOT, "%.0f mote-hours replayed.%n%n", moteHours));
        Map<HealthReplay.Reference, Long> refTicks = new LinkedHashMap<>();
        for (HealthReplay.Result r : rs) {
            r.referenceTicks().forEach((k, n) -> refTicks.merge(k, n, Long::sum));
        }
        md.append("Reference (heuristic) share of mote-time: ");
        for (HealthReplay.Reference ref : HealthReplay.Reference.values()) {
            md.append(String.format(Locale.ROOT, "%s %.1f%%; ", ref, 100.0 * refTicks.getOrDefault(ref, 0L) / ticks));
        }
        md.append("\n\n| Rule | Motes flagged | Episodes | Median episode (min) | Flagged mote-hours |\n|---|---|---|---|---|\n");
        List<HealthReplay.Episode> all = rs.stream().flatMap(r -> r.episodes().stream()).toList();
        for (HealthIssue i : HealthReplay.RULES) {
            List<HealthReplay.Episode> e = all.stream().filter(x -> x.issue() == i).toList();
            long motes = e.stream().map(HealthReplay.Episode::mote).distinct().count();
            double hours = e.stream().mapToLong(x -> x.length().toSeconds()).sum() / 3600.0;
            List<Long> mins = e.stream().map(x -> x.length().toMinutes()).sorted().toList();
            md.append(String.format(Locale.ROOT, "| %s | %d | %d | %s | %.0f |%n", i, motes, e.size(),
                    mins.isEmpty() ? "–" : String.valueOf(mins.get(mins.size() / 2)), hours));
        }
        md.append("\nPrecision / recall per detector against each reference, counted per evaluation tick (5 s of one mote). ")
          .append("SILENT is the OFFLINE rule's own definition, so that row only checks the replay mechanics.\n\n")
          .append("| Detector |");
        for (HealthReplay.Reference ref : HealthReplay.Reference.values()) {
            md.append(' ').append(ref).append(" P / R |");
        }
        md.append("\n|---|").append("---|".repeat(HealthReplay.Reference.values().length)).append('\n');
        List<String> detectors = new ArrayList<>(HealthReplay.RULES.stream().map(Enum::name).toList());
        detectors.add(HealthReplay.VALUE_RULES);
        detectors.add(HealthReplay.UNTRUSTED);
        detectors.add(HealthReplay.ROBUST_Z);
        for (String det : detectors) {
            md.append("| ").append(det).append(" |");
            for (HealthReplay.Reference ref : HealthReplay.Reference.values()) {
                HealthReplay.Confusion sum = new HealthReplay.Confusion();
                for (HealthReplay.Result r : rs) {
                    sum.add(r.confusion().get(new HealthReplay.Cell(det, ref)));
                }
                md.append(' ').append(f2(sum.precision())).append(" / ").append(f2(sum.recall())).append(" |");
                csv.append(String.join(",", v.name(), det, ref.name(), String.valueOf(sum.tp), String.valueOf(sum.fp),
                        String.valueOf(sum.fn), String.valueOf(sum.tn), f4(sum.precision()), f4(sum.recall()))).append('\n');
            }
            md.append('\n');
        }
        md.append("\nExamples (the three longest episodes per rule):\n\n| Rule | Mote | Start | Minutes | Evidence at opening |\n|---|---|---|---|---|\n");
        for (HealthIssue i : HealthReplay.RULES) {
            List<HealthReplay.Episode> top = all.stream().filter(x -> x.issue() == i)
                    .sorted(Comparator.comparing(HealthReplay.Episode::length).reversed()
                            .thenComparingInt(HealthReplay.Episode::mote)).limit(3).toList();
            for (HealthReplay.Episode e : top) {
                String ev = e.evidence() == null ? "" : e.evidence().entrySet().stream()
                        .map(x -> x.getKey() + "=" + x.getValue()).collect(Collectors.joining(", "));
                md.append(String.format(Locale.ROOT, "| %s | %d | %s | %d | %s |%n", i, e.mote(), e.start(),
                        e.length().toMinutes(), ev));
                epCsv.append(String.format(Locale.ROOT, "%s,%d,%s,%s,%s,%d,\"%s\"%n", v.name(), e.mote(), i, e.start(),
                        e.end(), e.length().toMinutes(), ev));
            }
        }
        md.append('\n');
    }

    private static String sha256(Path p) throws IOException {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(p)));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    private static String f2(double v) {
        return Double.isNaN(v) ? "–" : String.format(Locale.ROOT, "%.2f", v);
    }

    private static String f4(double v) {
        return Double.isNaN(v) ? "" : String.format(Locale.ROOT, "%.4f", v);
    }
}
